import XCTest
import AppKit
@testable import ConCopyCore

final class ClipboardMonitorTests: XCTestCase {
    @MainActor
    func testNormalStringIsCaptured() {
        let pasteboard = NSPasteboard.withUniqueName()
        let monitor = ClipboardMonitor(pasteboard: pasteboard)

        pasteboard.clearContents()
        let success = pasteboard.setString("Hello ConCopy", forType: .string)
        XCTAssertTrue(success)

        let captured = monitor.checkForChanges()
        XCTAssertNotNil(captured)
        XCTAssertEqual(captured?.content, "Hello ConCopy")
    }

    @MainActor
    func testConcealedTypeIsIgnored() {
        let pasteboard = NSPasteboard.withUniqueName()
        let monitor = ClipboardMonitor(pasteboard: pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString("SuperSecretPassword", forType: .string)
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        let success = pasteboard.writeObjects([item])
        XCTAssertTrue(success)

        let captured = monitor.checkForChanges()
        XCTAssertNil(captured)
    }

    @MainActor
    func testTransientTypeIsIgnored() {
        let pasteboard = NSPasteboard.withUniqueName()
        let monitor = ClipboardMonitor(pasteboard: pasteboard)

        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString("TransientData", forType: .string)
        item.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        let success = pasteboard.writeObjects([item])
        XCTAssertTrue(success)

        let captured = monitor.checkForChanges()
        XCTAssertNil(captured)
    }

    @MainActor
    func testAutoGeneratedAndOnePasswordTypesAreIgnored() {
        let pasteboard1 = NSPasteboard.withUniqueName()
        let monitor1 = ClipboardMonitor(pasteboard: pasteboard1)
        pasteboard1.clearContents()
        let item1 = NSPasteboardItem()
        item1.setString("AutoData", forType: .string)
        item1.setString("", forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
        XCTAssertTrue(pasteboard1.writeObjects([item1]))
        XCTAssertNil(monitor1.checkForChanges())

        let pasteboard2 = NSPasteboard.withUniqueName()
        let monitor2 = ClipboardMonitor(pasteboard: pasteboard2)
        pasteboard2.clearContents()
        let item2 = NSPasteboardItem()
        item2.setString("1PasswordSecret", forType: .string)
        item2.setString("", forType: NSPasteboard.PasteboardType("com.agilebits.onepassword"))
        XCTAssertTrue(pasteboard2.writeObjects([item2]))
        XCTAssertNil(monitor2.checkForChanges())
    }
}
