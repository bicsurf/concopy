import AppKit
import Foundation

@MainActor
public final class ClipboardMonitor {
    private let pasteboard: NSPasteboard
    private var lastChangeCount: Int
    private var timer: Timer?
    private var isRunning: Bool = false

    private let itemContinuation: AsyncStream<ClipboardItem>.Continuation
    public let stream: AsyncStream<ClipboardItem>

    private let clipContinuation: AsyncStream<CapturedClip>.Continuation
    public let capturedClipStream: AsyncStream<CapturedClip>

    public var onNewItem: ((ClipboardItem) -> Void)?
    public var onNewCapturedClip: ((CapturedClip) -> Void)?

    public static let ignoredTypeIdentifiers: Set<String> = [
        "org.nspasteboard.TransientType",
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.local.ConCopy.internalPaste"
    ]

    private static let targetUTIs = [
        "public.utf8-plain-text",
        "public.rtf",
        "public.html",
        "public.png",
        "public.tiff",
        "public.file-url",
        "public.url"
    ]

    public var settingsManager: AppSettingsManager
    public var frontmostAppBundleIdProvider: () -> String?

    public init(
        pasteboard: NSPasteboard = .general,
        captureInitialState: Bool = false,
        settingsManager: AppSettingsManager? = nil,
        frontmostAppBundleIdProvider: (@escaping () -> String?) = {
            NSWorkspace.shared.frontmostApplication?.bundleIdentifier
        }
    ) {
        self.pasteboard = pasteboard
        self.lastChangeCount = captureInitialState ? -1 : pasteboard.changeCount
        self.settingsManager = settingsManager ?? .shared
        self.frontmostAppBundleIdProvider = frontmostAppBundleIdProvider

        let (iStream, iCont) = AsyncStream.makeStream(of: ClipboardItem.self)
        self.stream = iStream
        self.itemContinuation = iCont

        let (cStream, cCont) = AsyncStream.makeStream(of: CapturedClip.self)
        self.capturedClipStream = cStream
        self.clipContinuation = cCont
    }

    deinit {
        timer?.invalidate()
        itemContinuation.finish()
        clipContinuation.finish()
    }

    public func start(pollingInterval: TimeInterval = 0.25) {
        guard !isRunning else { return }
        isRunning = true
        timer = Timer.scheduledTimer(withTimeInterval: pollingInterval, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in
                self?.checkForChanges()
            }
        }
        if let timer {
            RunLoop.main.add(timer, forMode: .common)
        }
    }

    public func stop() {
        isRunning = false
        timer?.invalidate()
        timer = nil
    }

    @discardableResult
    public func checkForChanges() -> ClipboardItem? {
        guard let captured = captureCurrentClip() else {
            return nil
        }

        let item = ClipboardItem(
            content: captured.plainText ?? "",
            sourceAppBundleID: captured.sourceAppBundleId,
            timestamp: Date(),
            capturedClip: captured
        )

        itemContinuation.yield(item)
        onNewItem?(item)
        return item
    }

    @discardableResult
    public func captureCurrentClip() -> CapturedClip? {
        let currentChangeCount = pasteboard.changeCount
        guard currentChangeCount != lastChangeCount else {
            return nil
        }
        lastChangeCount = currentChangeCount

        if settingsManager.isMonitoringPaused {
            return nil
        }

        guard !hasIgnoredTypes() else {
            return nil
        }

        let sourceApp = frontmostAppBundleIdProvider()
        if settingsManager.isAppExcluded(bundleId: sourceApp) {
            return nil
        }

        var representations: [String: Data] = [:]
        let rawText = pasteboard.string(forType: .string)

        if let text = rawText, !text.isEmpty {
            representations["public.utf8-plain-text"] = Data(text.utf8)
        }

        for uti in Self.targetUTIs {
            if uti == "public.utf8-plain-text" && representations[uti] != nil {
                continue
            }
            if let data = pasteboard.data(forType: NSPasteboard.PasteboardType(uti)), !data.isEmpty {
                representations[uti] = data
            }
        }

        guard !representations.isEmpty || (rawText != nil && !rawText!.isEmpty) else {
            return nil
        }

        let primaryType = Self.determinePrimaryType(
            plainText: rawText,
            representations: representations
        )

        let captured = CapturedClip(
            plainText: rawText,
            primaryType: primaryType,
            sourceAppBundleId: sourceApp,
            representations: representations
        )

        clipContinuation.yield(captured)
        onNewCapturedClip?(captured)
        return captured
    }

    public nonisolated static func determinePrimaryType(
        plainText: String?,
        representations: [String: Data]
    ) -> ClipPrimaryType {
        let hasImage = representations["public.png"] != nil || representations["public.tiff"] != nil
        let hasText = plainText != nil && !(plainText?.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty ?? true)
        let hasRTF = representations["public.rtf"] != nil
        let hasHTML = representations["public.html"] != nil
        let hasFileURL = representations["public.file-url"] != nil

        if hasFileURL {
            return .file
        }

        if hasImage && !hasText {
            return .image
        }

        if let text = plainText?.trimmingCharacters(in: .whitespacesAndNewlines), !text.isEmpty {
            if isValidURL(text) {
                return .url
            }
            if hasRTF {
                return .richText
            }
            if hasHTML {
                return .html
            }
            if hasImage {
                return .richText
            }
            return .text
        }

        if hasImage {
            return .image
        }

        if hasRTF {
            return .richText
        }

        if hasHTML {
            return .html
        }

        return .text
    }

    private nonisolated static func isValidURL(_ string: String) -> Bool {
        guard let url = URL(string: string), let scheme = url.scheme?.lowercased() else {
            return false
        }
        return (scheme == "http" || scheme == "https" || scheme == "ftp") && url.host != nil
    }

    private func hasIgnoredTypes() -> Bool {
        if let types = pasteboard.types {
            for type in types {
                if Self.ignoredTypeIdentifiers.contains(type.rawValue) {
                    return true
                }
            }
        }
        if let items = pasteboard.pasteboardItems {
            for item in items {
                for type in item.types {
                    if Self.ignoredTypeIdentifiers.contains(type.rawValue) {
                        return true
                    }
                }
            }
        }
        return false
    }
}
